    <script>
        const menuBtn = document.getElementById('menuBtn');
        const closeMenuBtn = document.getElementById('closeMenuBtn');
        const mobileMenu = document.getElementById('mobileMenu');
        const mobileMenuOverlay = document.getElementById('mobileMenuOverlay');

        function toggleMenu() {
            mobileMenu.classList.toggle('-translate-x-full');
            mobileMenuOverlay.classList.toggle('hidden');
        }

        menuBtn.addEventListener('click', toggleMenu);
        closeMenuBtn.addEventListener('click', toggleMenu);
        mobileMenuOverlay.addEventListener('click', toggleMenu);

        // Auth Modal Elements & Logic
        const authModal = document.getElementById('authModal');
        const authModalContent = document.getElementById('authModalContent');
        const closeAuthModal = document.getElementById('closeAuthModal');
        const openAuthModalDesk = document.getElementById('openAuthModalDesk');
        const openAuthModalMob = document.getElementById('openAuthModalMob');
        const openAuthModalBottom = document.getElementById('openAuthModalBottom');

        function showAuthModal() {
            authModal.classList.remove('hidden');
            setTimeout(() => authModalContent.classList.remove('scale-95'), 10);
            if(!mobileMenu.classList.contains('-translate-x-full')) {
                toggleMenu();
            }
        }

        function hideAuthModal() {
            authModalContent.classList.add('scale-95');
            setTimeout(() => authModal.classList.add('hidden'), 200);
        }

        if(openAuthModalDesk) openAuthModalDesk.addEventListener('click', showAuthModal);
        if(openAuthModalMob) openAuthModalMob.addEventListener('click', showAuthModal);
        if(openAuthModalBottom) openAuthModalBottom.addEventListener('click', showAuthModal);
        if(closeAuthModal) closeAuthModal.addEventListener('click', hideAuthModal);
        
        authModal.addEventListener('click', (e) => {
            if (e.target === authModal) hideAuthModal();
        });
    </script>

